"""Generate the ConceptMap FSH files in input/fsh/maps from the CSV files here.

Each CSV describes the mapping of one logical model onto one profile, with the
columns sourceCode, sourceDisplay, relationship, targetCode, targetDisplay, comment.
The comment column ends up as ConceptMap.group.element.target.comment, which is
what the conceptmap table template renders in its "Notes" column.

Usage:  python mappings/generate-conceptmaps.py
"""
import csv
import io
import os

CANONICAL = "https://www.ehealth.fgov.be/standards/fhir/core-clinical"
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "input", "fsh", "maps")

# csv file -> (instance id, title, source model id, target profile id)
MAPS = [
    (
        "BeModelEncounter-to-BeEncounter.csv",
        "BeModelEncounter2BeEncounter",
        "BeModelEncounter to BeEncounter Mapping",
        "BeModelEncounter",
        "be-encounter",
    ),
    (
        "BeModelEpisodeOfCare-to-BeEpisodeOfCare.csv",
        "BeModelEpisodeOfCare2BeEpisodeOfCare",
        "BeModelEpisodeOfCare to BeEpisodeOfCare Mapping",
        "be-model-episode-of-care",
        "be-episode-of-care",
    ),
]


def esc(value):
    """Escape a value so it survives as a FSH RuleSet parameter."""
    return value.replace("\\", r"\\").replace(",", r"\,").replace(")", r"\)").replace('"', "'")


def generate(csv_name, instance, title, source_id, target_id):
    rows = list(csv.DictReader(io.open(os.path.join(HERE, csv_name), encoding="utf8")))
    source = "%s/StructureDefinition/%s" % (CANONICAL, source_id)
    target = "%s/StructureDefinition/%s" % (CANONICAL, target_id)

    out = []
    out.append("// Generated by mappings/generate-conceptmaps.py from mappings/%s" % csv_name)
    out.append("// Do not edit by hand - edit the CSV and regenerate.")
    out.append("")
    out.append("Instance: %s" % instance)
    out.append("InstanceOf: ConceptMap")
    out.append("Usage: #definition")
    out.append('* url = "%s/ConceptMap/%s"' % (CANONICAL, instance))
    out.append('* name = "%s"' % instance)
    out.append('* title = "%s"' % title)
    out.append("* status = #draft")
    out.append("* experimental = false")
    out.append('* description = "Mapping from %s (Logical Model) to %s"' % (source_id, target_id))
    out.append('* sourceUri = "%s"' % source)
    out.append('* targetUri = "%s"' % target)
    out.append("")
    out.append("* group[+]")
    out.append('  * source = "%s"' % source)
    out.append('  * target = "%s"' % target)
    for row in rows:
        if row["targetCode"]:
            out.append(
                "  * insert ConceptMapElement(%s, %s, %s, %s, %s, %s)"
                % (
                    esc(row["sourceCode"]),
                    esc(row["sourceDisplay"]),
                    esc(row["targetCode"]),
                    esc(row["targetDisplay"]),
                    esc(row["relationship"]),
                    esc(row["comment"]),
                )
            )
        else:
            out.append(
                "  * insert ConceptMapElementUnmapped(%s, %s, %s)"
                % (esc(row["sourceCode"]), esc(row["sourceDisplay"]), esc(row["comment"]))
            )
    out.append("")

    path = os.path.join(OUT, instance + ".fsh")
    io.open(path, "w", encoding="utf8", newline="\n").write("\n".join(out))
    print("%s -> %s (%d elements)" % (csv_name, os.path.relpath(path, ROOT), len(rows)))


if __name__ == "__main__":
    for entry in MAPS:
        generate(*entry)
